#!/usr/bin/env python3
"""Fetch the formatter's small, offline Twemoji set; never run at TV startup.

Artwork: Twemoji, Twitter, Inc. and other contributors, CC-BY 4.0.
https://github.com/jdecked/twemoji/tree/v16.0.1
No application compilation is involved. Requires only Python and Pillow.
"""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from io import BytesIO
from pathlib import Path
from urllib.request import urlopen
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BASE = 'https://raw.githubusercontent.com/jdecked/twemoji/v16.0.1'
SYMBOLS = [
    ('💾', 'hard-drive'), ('👤', 'users'), ('👥', 'users'), ('🎞', 'film'),
    ('🎬', 'clapperboard'), ('🎥', 'film'), ('🔊', 'volume-2'), ('🎧', 'volume-2'),
    ('🌐', 'globe'), ('⚙', 'settings-2'), ('⚡', 'zap'), ('📦', 'package'),
    ('🏷', 'tag'), ('⏱', 'clock'), ('📝', 'captions'), ('📺', 'monitor-play'),
    ('📁', 'folders'), ('🔗', 'link'), ('✅', 'check'), ('❌', 'x'),
    ('⭐', 'star'), ('🔥', 'sparkles'), ('🔒', 'key'), ('⏳', 'clock'),
    ('🚀', 'zap'), ('💬', 'message-square'), ('📊', 'chart-column'), ('📌', 'tag'),
]
COUNTRIES = 'PL GB US DE FR IT ES MX PT BR NL BE RU UA TR CZ SK SE NO DK FI HU RO BG GR HR RS BA SI LT LV EE IE CA AU NZ JP KR CN TW HK IN PK BD ID MY TH VN SA AE IL IR CH AT'.split()
for country in COUNTRIES:
    SYMBOLS.append((''.join(chr(0x1f1e6 + ord(c) - ord('A')) for c in country), 'globe'))

def codepoints(emoji):
    return '-'.join(f'{ord(c):x}' for c in emoji)

def main():
    destination = ROOT / 'deploy/app/art/icones'
    destination.mkdir(parents=True, exist_ok=True)
    def fetch(symbol):
        emoji, fallback = symbol
        code = codepoints(emoji)
        url = f'{BASE}/assets/72x72/{code}.png'
        data = urlopen(url, timeout=30).read()
        image = Image.open(BytesIO(data)).convert('RGBA')
        image.thumbnail((48, 48), Image.Resampling.LANCZOS)
        path = destination / f'emoji_{code}.png'
        image.save(path, optimize=True)
        return {'emoji': emoji, 'file': path.name, 'url': url,
                'sha256': sha256(path.read_bytes()).hexdigest()}
    with ThreadPoolExecutor(max_workers=8) as executor:
        manifest = list(executor.map(fetch, SYMBOLS))
    (destination / 'emoji-attribution.txt').write_text(
        'Twemoji graphics by Twitter, Inc. and other contributors.\n'
        'Licensed under Creative Commons Attribution 4.0 International (CC BY 4.0).\n'
        'https://creativecommons.org/licenses/by/4.0/\n'
        'https://github.com/jdecked/twemoji/tree/v16.0.1\n'
        'Adaptation: resized from 72 x 72 to 48 x 48 pixels for Nuvio Native Legacy.\n', encoding='utf-8')
    license_text = urlopen(f'{BASE}/LICENSE-GRAPHICS', timeout=30).read().decode('utf-8')
    (destination / 'emoji-license.txt').write_text(
        '\n'.join(line.rstrip() for line in license_text.splitlines()) + '\n', encoding='utf-8')
    (destination / 'emoji-manifest.json').write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    table = ['// Generated by tools/formatter_emoji_assets.py; Twemoji CC-BY 4.0.',
             'static const struct { const char *emoji, *icone, *reserva; } EMOJI_ICONE[] = {']
    for emoji, fallback in SYMBOLS:
        table.append(f'  {{ "{emoji}", "emoji_{codepoints(emoji)}", "aj_{fallback}" }},')
    # Formatter marker, not an actual country's flag.
    table.append('  { "⚑", "emoji_1f310", "aj_globe" },')
    table.append('};')
    (ROOT / 'src/stream_formatter_emoji.inc').write_text('\n'.join(table) + '\n', encoding='utf-8')
    print(f'Saved {len(manifest)} local emoji/flag assets.')

if __name__ == '__main__':
    main()
